"""Response schema and validation for Groq-generated repair proposals."""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class PatchChange(BaseModel):
    """Represents a single atomic patch operation."""
    path: str = Field(..., description="Repository-relative file path to modify")
    operation: Literal["replace", "create", "delete"] = Field(
        default="replace",
        description="Patch operation type"
    )
    original: str = Field(
        ...,
        description="Exact fragment of original text to replace (for 'replace' op)"
    )
    replacement: str = Field(
        ...,
        description="Exact replacement text to insert"
    )
    reason: str = Field(
        ...,
        description="Explanation for why this specific change is necessary"
    )

    @field_validator("path")
    @classmethod
    def validate_path_safety(cls, v: str) -> str:
        cleaned = v.strip().replace("\\", "/")
        if cleaned.startswith("/") or cleaned.startswith("~"):
            raise ValueError(f"Path must be relative, got: {v}")
        if ".." in cleaned.split("/"):
            raise ValueError(f"Path traversal detected in path: {v}")
        return cleaned

    @field_validator("original", "replacement")
    @classmethod
    def validate_strings(cls, v: str) -> str:
        # String cannot be None
        if v is None:
            raise ValueError("Patch string cannot be None")
        return v


class RepairProposal(BaseModel):
    """Structured proposal generated by Groq LLM for self-healing repair."""
    category: Literal[
        "dependency_version",
        "dockerfile_error",
        "unit_test_regression",
        "unsupported"
    ] = Field(..., description="Classified failure category")
    diagnosis: str = Field(..., min_length=5, description="Clear description of the root cause")
    root_cause_evidence: List[str] = Field(
        default_factory=list,
        description="Concrete log lines or code evidence supporting diagnosis"
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Agent confidence in this diagnosis and fix (0.0 - 1.0)"
    )
    changes: List[PatchChange] = Field(
        default_factory=list,
        description="List of file modifications proposed"
    )
    validation_plan: List[str] = Field(
        default_factory=list,
        description="List of verification steps or test commands"
    )

    @model_validator(mode="after")
    def validate_proposal_integrity(self) -> "RepairProposal":
        if self.category != "unsupported" and not self.changes:
            raise ValueError("Supported failure categories must propose at least one change.")
        if self.category == "unsupported" and self.changes:
            raise ValueError("Unsupported failure category should not propose code changes.")
        return self


def parse_and_validate_proposal(raw_json: dict) -> RepairProposal:
    """Parses raw dictionary into validated RepairProposal, raising ValueError on violation."""
    return RepairProposal.model_validate(raw_json)
